import AgentMonitorPresentation
import Darwin
import Foundation

@main
enum PreviewCommand {
    static func main() {
        do {
            let arguments = Array(CommandLine.arguments.dropFirst())
            guard arguments.count == 2, ["update", "check"].contains(arguments[0]) else {
                throw PreviewError.message("Usage: monitor-preview update|check <output.svg>")
            }
            let lines = LiveReportLayout.lines(state: try Preview.state(), width: 120, height: 19)
            let svg = Preview.svg(lines: lines, width: 120, height: 19)
            let output = URL(fileURLWithPath: arguments[1])
            switch arguments[0] {
            case "update":
                try svg.write(to: output, atomically: true, encoding: .utf8)
                print("Updated \(output.lastPathComponent); visually review before committing.")
            default:
                try Preview.check(at: output, expected: svg)
                print("README preview is current.")
            }
        } catch {
            FileHandle.standardError.write(Data("\(error.localizedDescription)\n".utf8))
            exit(1)
        }
    }
}

enum PreviewError: LocalizedError {
    case message(String)

    var errorDescription: String? {
        switch self {
        case .message(let message): message
        }
    }
}

enum Preview {
    static func check(at url: URL, expected: String) throws {
        guard (try? Data(contentsOf: url)) == Data(expected.utf8) else {
            throw PreviewError.message(
                "README preview is missing or stale. Run bash scripts/preview.sh update, review it, and commit the SVG."
            )
        }
    }

    static func svg(lines: [ReportLine], width: Int, height: Int) -> String {
        let pixelsWide = width * 9 + 48
        let pixelsHigh = height * 23 + 68
        var output = """
            <svg xmlns="http://www.w3.org/2000/svg" width="\(pixelsWide)" height="\(pixelsHigh)" viewBox="0 0 \(pixelsWide) \(pixelsHigh)" role="img" aria-labelledby="title description">
            <title id="title">Agent Monitor terminal UI with synthetic process data</title>
            <desc id="description">Illustrative process view from the production layout renderer with details open. All process IDs, session IDs, paths, and usage values are synthetic.</desc>
            <!-- Generated by bash scripts/preview.sh update. Edit Tools/Preview, not this file. -->
            <rect width="\(pixelsWide)" height="\(pixelsHigh)" rx="12" fill="#0d1117"/>
            <path d="M12 0H\(pixelsWide - 12)Q\(pixelsWide) 0 \(pixelsWide) 12V44H0V12Q0 0 12 0Z" fill="#21262d"/>
            <circle cx="22" cy="22" r="6" fill="#ff5f57"/><circle cx="43" cy="22" r="6" fill="#febc2e"/><circle cx="64" cy="22" r="6" fill="#28c840"/>
            <text x="\(pixelsWide / 2)" y="27" text-anchor="middle" fill="#c9d1d9" font-family="sans-serif" font-size="13">agent-monitor · process view</text>
            <text x="\(pixelsWide - 24)" y="27" text-anchor="end" fill="#8b949e" font-family="sans-serif" font-size="11">SYNTHETIC DATA</text>
            <g font-family="Menlo, DejaVu Sans Mono, monospace" font-size="15">

            """
        for (index, line) in lines.enumerated() {
            let text = line.text.replacingOccurrences(of: "\\s+$", with: "", options: .regularExpression)
            guard !text.isEmpty else { continue }
            let color: String
            let weight: String
            switch line.style {
            // Approximates the TUI's SwiftTUI 0.14.0 colors (ShapeStyles.swift) on a dark theme.
            case .title: (color, weight) = ("#5ba3ff", "bold")
            case .heading: (color, weight) = ("#f0f6fc", "bold")
            case .selected, .separator: (color, weight) = ("#79e4ff", "bold")
            case .heavy, .warning: (color, weight) = ("#e3b341", "normal")
            case .muted: (color, weight) = ("#8c92ac", "normal")
            case .success: (color, weight) = ("#61c67b", "normal")
            case .failure: (color, weight) = ("#e05757", "normal")
            case .normal: (color, weight) = ("#c9d1d9", "normal")
            }
            // SVG 2 lengthAdjust can scale glyphs; terminal cells need positions, not fitted text.
            // https://www.w3.org/TR/SVG2/text.html#TextElementLengthAdjustAttribute
            var column = 0
            let glyphs = text.compactMap { character -> String? in
                defer { column += TerminalCells.width(character) }
                guard character != " " else { return nil }
                return "<tspan x=\"\(24 + column * 9)\">\(escape(String(character)))</tspan>"
            }.joined()
            output += """
                <text y="\(69 + index * 23)" fill="\(color)" font-weight="\(weight)" aria-label="\(escape(text))">\(glyphs)</text>

                """
        }
        return output + "</g>\n</svg>\n"
    }

    private static func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "'", with: "&apos;")
    }
}
